import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { credentialConsumers, formalDataWritableChildren, internalPorts, serviceIdentity, validateProductionSessionSecurity, windowsAclContract } from "./windows-security-foundation.mjs";
import { parseWindowsCredentialBundle } from "./windows-credential-bundle.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const contract = JSON.parse(await readFile(path.join(root, "service", "windows", "security-foundation.contract.json"), "utf8"));
const webConfig = await readFile(path.join(root, "service", "windows", "UEDAssetHubEdge.web.config.template"), "utf8");
const aclProvisioning = await readFile(path.join(root, "scripts", "provision-windows-security-foundation.ps1"), "utf8");
const tlsProvisioning = await readFile(path.join(root, "scripts", "provision-windows-iis-tls.ps1"), "utf8");
const firewallProvisioning = await readFile(path.join(root, "scripts", "provision-windows-firewall.ps1"), "utf8");
const nativeHarness = await readFile(path.join(root, "scripts", "windows-security-foundation-harness.ps1"), "utf8");
const dpapiHelper = await readFile(path.join(root, "native", "windows-dpapi-credential-helper", "ued_windows_dpapi_credential_helper.cpp"), "utf8");
assert.deepEqual(contract.service, { account: serviceIdentity.account, sidType: "unrestricted", forbiddenAccounts: ["LocalSystem", "Administrators"] });
assert.equal(contract.credentials.provider, "dpapi");
assert.equal(contract.credentials.scope, "machine");
assert.equal(contract.edge.upstream, "http://127.0.0.1:3027");
assert.equal(contract.edge.httpsPort, 443);
assert.equal(contract.edge.httpPort, "closed");
assert.equal(contract.edge.responseBuffering, false);
assert.match(webConfig, /127\.0\.0\.1:3027/);
assert.match(webConfig, /webSocket enabled="true"/);
assert.equal(contract.tls.store, "LocalMachine\\My");
assert.equal(contract.tls.minimumRemainingDays, 30);
assert.deepEqual(contract.firewall.denyInbound, [80, ...internalPorts]);
assert.deepEqual(contract.formalDataWritableChildren, formalDataWritableChildren);
assert.deepEqual(windowsAclContract(), { service: "RX", releases: "RX", current: "RX_TRAVERSE", staging: "NONE", dshSource: "RX", agentRuntime: "MODIFY", assetHubRuntime: "MODIFY", trainingMedia: "MODIFY", logs: "MODIFY_APPEND", config: "READ", credentials: "READ", formalDataRoot: "READ_TRAVERSE", formalDataWritableChildren: "MODIFY", backup: "NONE" });
assert.deepEqual(credentialConsumers.DEEPSEEK_API_KEY, ["dsh"]);
assert.deepEqual(credentialConsumers.AGENT_GATEWAY_TOKEN, ["assetHub", "gateway"]);
assert.equal(validateProductionSessionSecurity({ NODE_ENV: "production", ADMIN_SESSION_SECURE: "true", PUBLIC_ORIGIN: "https://asset-hub.test" }).ok, true);
assert.equal(validateProductionSessionSecurity({ NODE_ENV: "production", ADMIN_SESSION_SECURE: "false", PUBLIC_ORIGIN: "https://asset-hub.test" }).ok, false);
assert.equal(validateProductionSessionSecurity({ NODE_ENV: "production", ADMIN_SESSION_SECURE: "true", PUBLIC_ORIGIN: "http://asset-hub.test" }).ok, false);
assert.deepEqual(parseWindowsCredentialBundle(JSON.stringify({ schemaVersion: 1, credentials: { adminPassword: "password", adminSessionSecret: "x".repeat(32), deepseekApiKey: "key", gatewayToken: "token", testEnvironmentEncryptionKey: "test-key" } })), { ADMIN_PASSWORD: "password", ADMIN_SESSION_SECRET: "x".repeat(32), DEEPSEEK_API_KEY: "key", AGENT_GATEWAY_TOKEN: "token", TEST_ENV_ENCRYPTION_KEY: "test-key" });
assert.throws(() => parseWindowsCredentialBundle(JSON.stringify({ schemaVersion: 1, credentials: {} })));
assert.match(aclProvisioning, /ValidateSet\('DryRun','Apply','Verify'\)/);
assert.match(aclProvisioning, /UNC paths are forbidden/);
assert.match(aclProvisioning, /ReparsePoint/);
assert.match(aclProvisioning, /sc\.exe sidtype UEDAssetHub unrestricted/);
assert.match(aclProvisioning, /Formal DATA root must already exist/);
assert.match(aclProvisioning, /Assert-NoServiceWrite \$formal/);
assert.match(aclProvisioning, /Assert-NoServiceAccess \$backup/);
assert.match(aclProvisioning, /icacls\.exe \$Path \/remove:g \$sid/);
assert.match(tlsProvisioning, /Cert:\\LocalMachine\\My/);
assert.match(tlsProvisioning, /EnhancedKeyUsageList/);
assert.match(tlsProvisioning, /DnsNameList/);
assert.match(tlsProvisioning, /New-WebBinding/);
assert.match(tlsProvisioning, /Remove-WebBinding/);
assert.match(firewallProvisioning, /New-NetFirewallRule/);
assert.match(firewallProvisioning, /Private approved LAN scope cannot be Any/);
assert.match(firewallProvisioning, /Get-NetFirewallRule -Enabled True/);
assert.doesNotMatch(firewallProvisioning, /advfirewall reset/i);
assert.match(dpapiHelper, /CryptProtectData/);
assert.match(dpapiHelper, /CryptUnprotectData/);
assert.match(dpapiHelper, /CRYPTPROTECT_LOCAL_MACHINE/);
assert.doesNotMatch(dpapiHelper, /system\s*\(|ShellExecute|CreateProcess|WinHttp|WSAStartup/i);
assert.match(nativeHarness, /-Action Verify/);
assert.match(nativeHarness, /DPAPI machine-scope decryptability check failed/);
assert.match(nativeHarness, /TLS private key/);
console.log("[UED Agent] Windows security foundation static contract checks passed.");
