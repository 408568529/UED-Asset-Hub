import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import path from "node:path";
import { assertB4bEvidence, createB4bIdentity, renderB4bWinSwTemplate } from "./b4b-service-contract.mjs";
import { verifyCandidateRuntimeObservability } from "./candidate-runtime-closure.mjs";

const root = path.resolve(import.meta.dirname, "..");
const identity = createB4bIdentity("g036b-20260922-a1b2c3d4");
const template = await readFile(path.join(root, "service", "windows", "UEDAssetHub.xml.template"), "utf8");
const rendered = renderB4bWinSwTemplate(template, { root: "D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4", identity });
const serviceE2e = await readFile(path.join(root, "scripts", "run-b4b-service-e2e.mjs"), "utf8");
const observability = await verifyCandidateRuntimeObservability({ candidateRoot: root });
assert.equal(observability.result, "PASS");
assert.match(rendered, new RegExp(`<id>${identity.serviceName}</id>`));
assert.match(rendered, new RegExp(`service\\\\${identity.serviceName}\\.exe`));
assert.match(rendered, /<env name="NODE_ENV" value="production" \/>/);
assert.match(rendered, /<startmode>Manual<\/startmode>/);
assert.match(serviceE2e, /dpapiHelperIdentity:\s*provisioned\.evidence\.dpapiHelperSha256\s*===\s*deployment\.components\?\.windowsDpapiHelper\?\.sha256/u);
assert.match(serviceE2e, /verifyCandidateRuntimeObservability\(\{ candidateRoot \}\)/u, "B4B requires an observability gate before service install");
assert.match(serviceE2e, /SCM_STOP_REQUESTED[\s\S]*stopRequestTime/u, "B4B persists the single controlled-stop request time");
assert.match(serviceE2e, /postStopNewGenerationCount !== 0/u, "B4B rejects post-stop Asset Hub generations");
assert.match(serviceE2e, /!stopRequestAttempted && state\.serviceState === "Running"/u, "B4B does not retry a pending controlled stop");
assert.equal(serviceE2e.includes("d4834ad6c9ef9185642868daee1bff79feb8b6e39e8926812c26814ea08b9403"), false);
assert.match(rendered, /<env name="DATA_DIR" value="D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4\\runtime-data" \/>/);
assert.match(rendered, /<env name="ASSET_HUB_RUNTIME_DIR" value="D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4\\asset-hub-runtime" \/>/);
assert.match(rendered, /<env name="UED_CREDENTIAL_BUNDLE_PATH" value="D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4\\credentials\\UEDAssetHub-B4B-g036b-20260922-a1b2c3d4\.credentials\.dpapi" \/>/);
assert.match(rendered, /<env name="DSH_SOURCE_DIR" value="D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4\\dsh-git-authority-v2" \/>/);
assert.match(rendered, /<env name="DSH_RUNTIME_SOURCE_DIR" value="D:\\UED-Asset-Hub-Staging\\b4b\\g036b-20260922-a1b2c3d4\\dsh-runtime-v2" \/>/);
assert.equal(rendered.includes("{{"), false);
assert.deepEqual(assertB4bEvidence({ b4bRunId: identity.b4bRunId, phase: "precheck", status: "pass" }, identity.b4bRunId).status, "pass");
assert.throws(() => assertB4bEvidence({ b4bRunId: identity.b4bRunId, token: "forbidden" }, identity.b4bRunId));
assert.throws(() => assertB4bEvidence({ b4bRunId: "other", phase: "precheck" }, identity.b4bRunId));
console.log("[UED Agent] B4B service contract passed.");
